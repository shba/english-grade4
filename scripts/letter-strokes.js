/** Strokes for one letter in letter-box coordinates (0..1), with optional random wobble and slant. */
export function letterStrokes(ch, { jitter = 0, slant = 0, scale = 1, dx = 0 } = {}, rnd = Math.random) {
  const top = 0.12, h = 0.6;
  const w = (ch === ch.toLowerCase() ? 0.42 : 0.56) * scale;
  return STROKES[ch].map((s) => {
    // densify so jitter looks like a hand-drawn line
    const dense = [];
    for (let i = 0; i < s.length; i++) {
      dense.push(s[i]);
      if (i + 1 < s.length) {
        const [x0, y0] = s[i], [x1, y1] = s[i + 1];
        const n = Math.ceil(Math.hypot(x1 - x0, y1 - y0) / 0.08);
        for (let k = 1; k < n; k++) dense.push([x0 + ((x1 - x0) * k) / n, y0 + ((y1 - y0) * k) / n]);
      }
    }
    return dense.map(([x, y]) => {
      const yy = top + h * y;
      const xx = 0.5 + dx + (x - 0.5) * w + slant * (0.72 - yy);
      return { x: xx + (rnd() - 0.5) * jitter, y: yy + (rnd() - 0.5) * jitter };
    });
  });
}
